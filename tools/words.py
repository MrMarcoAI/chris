    seen = set()
    for w, c, l, t in WORDS:
        assert re.fullmatch(r"[A-ZÑ]{3,11}", w), f"Palabra inválida: {w}"
        assert w not in seen, f"Duplicada: {w}"
        import unicodedata
        plain = unicodedata.normalize("NFD", c.upper())
        plain = "".join(ch for ch in plain if not unicodedata.combining(ch) or ch == "̃")
        plain = unicodedata.normalize("NFC", plain)
        assert c and not re.search(rf"\b{w}\b", plain), f"La pista revela la respuesta: {w}"
        assert l in (1, 2, 3), f"Nivel inválido: {w}"
        seen.add(w)
    print(f"{len(WORDS)} palabras OK")


